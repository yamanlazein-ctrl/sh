export function norm(s: string): string {
  return s
    .replace(/[\u064B-\u0652\u0670\u0640]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .toLowerCase();
}

function stripAl(t: string): string {
  if (t.startsWith("ال") && t.length > 4) return t.slice(2);
  if (t.startsWith("وال") && t.length > 5) return t.slice(3);
  return t;
}

const INDEX = ITEMS.map((i) => ({
  item: i,
  title: norm(i.title),
  tags: norm(i.tags.join(" ")),
  excerpt: norm(i.excerpt),
  body: norm(i.body),
}));

export function tokenize(q: string): string[] {
  return norm(q)
    .split(/\s+/)
    .map((t) => stripAl(t.trim()))
    .filter((t) => t.length > 1);
}

export function searchArchive(q: string, filter?: (i: ArchiveItem) => boolean) {
  const tokens = tokenize(q);
  const pool = filter ? INDEX.filter((x) => filter(x.item)) : INDEX;
  if (tokens.length === 0) {
    return { results: pool.map((x) => x.item), tokens };
  }

  const scored = pool
    .map((x) => {
      let score = 0;
      for (const t of tokens) {
        if (x.title.includes(t)) score += 6;
        if (x.tags.includes(t)) score += 4;
        if (x.excerpt.includes(t)) score += 2;
        if (x.body.includes(t)) score += 1;
        const syn = SYNONYMS[t] || [];
        for (const s of syn) {
          if (x.title.includes(s)) score += 2;
          if (x.tags.includes(s)) score += 2;
          if (x.excerpt.includes(s)) score += 1;
        }
      }
      return { item: x.item, score };
    })
    .filter((x) => x.score >= 4)
    .sort((a, b) => b.score - a.score)
    .map((x) => x.item);

  return { results: scored, tokens };
}

// يقسم النص إلى أجزاء مع تمييز الكلمات المطابقة (النصوص بدون تشكيل فالمواقع متطابقة)
export function highlight(text: string, tokens: string[]) {
  if (tokens.length === 0) return [{ text, hit: false }];
  const n = norm(text);
  const marks = new Array(text.length).fill(false);
  for (const t of tokens) {
    let idx = n.indexOf(t);
    while (idx !== -1) {
      for (let k = idx; k < idx + t.length && k < marks.length; k++) marks[k] = true;
      idx = n.indexOf(t, idx + t.length);
    }
  }
  const parts: { text: string; hit: boolean }[] = [];
  for (let i = 0; i < text.length; i++) {
    const last = parts[parts.length - 1];
    if (last && last.hit === marks[i]) last.text += text[i];
    else parts.push({ text: text[i], hit: marks[i] });
  }
  return parts;
}
